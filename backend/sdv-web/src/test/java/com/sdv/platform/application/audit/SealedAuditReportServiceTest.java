/**
 * Task 0050: the sealed audit report. Its CSV carries the stamp and the events (document IDs and record identifiers,
 * never content, file names, titles or reasons); the fingerprint is the SHA-256 of that CSV; the register and the
 * audit are written together or not at all; the PDF is made from the same CSV; verify passes for an unchanged file
 * and fails for a changed one.
 */
class SealedAuditReportServiceTest {
    private static final UUID TENANT = UUID.fromString("11111111-1111-1111-1111-111111111111");
    private static final UUID OTHER = UUID.fromString("22222222-2222-2222-2222-222222222222");
    private static final UUID DOC = UUID.fromString("d0c00000-0000-4000-8000-000000000001");
    private static final Instant NOW = Instant.parse("2026-11-23T09:30:00Z");

    private final AuditQueryService audits = mock(AuditQueryService.class);
    private final List<AuditEvent> events = new ArrayList<>();
    private final AuditEventPort audit = events::add;
    private final Register register = new Register();
    private SealedAuditReportService service;

    private static final SealedAuditReportService.Actor PRIYA =
            new SealedAuditReportService.Actor(TENANT, "local-business-admin", "Priya Natarajan", "corr-1");

    @BeforeEach
    void setUp() {
        service = new SealedAuditReportService(audits, register, audit, mock(PlatformTransactionManager.class),
                Clock.fixed(NOW, ZoneOffset.UTC));
    }

    /** Events whose details carry a file name, a title and a reason, as some audit rows do: none may reach the report. */
    private static List<AuditQueryService.AuditEntry> entries() {
        String secrets = "{\"originalFilename\":\"secret-loan-agreement.pdf\",\"title\":\"Jane Borrower loan\",\"reason\":\"Top secret reason\"}";
        return List.of(
                new AuditQueryService.AuditEntry(UUID.randomUUID(), "USER", "local-business-user", "DOCUMENT_VIEW_OPENED", "DOCUMENT",
                        DOC.toString(), Instant.parse("2026-11-20T10:00:00Z"), "c1", AuditOutcome.SUCCESS, secrets, "Maya Okafor",
                        "300000000001", DOC, SensitivityLevel.CONFIDENTIAL, Instant.parse("2026-11-01T08:00:00Z"), 4),
                new AuditQueryService.AuditEntry(UUID.randomUUID(), "USER", "local-document-steward", "DOCUMENT_ACCESS_REFUSED", "DOCUMENT",
                        DOC.toString(), Instant.parse("2026-11-21T11:00:00Z"), "c2", AuditOutcome.DENIED, secrets, "Daniel Reyes",
                        "300000000001", DOC, SensitivityLevel.CONFIDENTIAL, Instant.parse("2026-11-01T08:00:00Z"), 4));
    }

    private static SealedAuditReportService.ReportRequest days(String from, String to) {
        return new SealedAuditReportService.ReportRequest(from, to, null, null, null, null);
    }

    @Test
    void theCsvIsStampedAndHoldsNoContentFileNameTitleOrReason() {
        when(audits.sealedEntries(eq(TENANT), any())).thenReturn(entries());
        SealedAuditReportService.Report report = service.generate(PRIYA,
                new SealedAuditReportService.ReportRequest("2026-11-01", "2026-11-22", null, "SUCCESS", " 300000000001 ", null));

        String csv = new String(register.only().csv(), StandardCharsets.UTF_8);
        assertTrue(csv.startsWith("﻿\"Vero sealed audit report\"\r\n"));
        assertTrue(csv.contains("\"Report\",\"" + report.reportId() + "\""));
        assertTrue(csv.contains("\"Generated by\",\"Priya Natarajan\""));
        assertTrue(csv.contains("\"Generated at (UTC)\",\"2026-11-23T09:30:00Z\""));
        assertTrue(csv.contains("\"First day (UTC)\",\"2026-11-01\""));
        assertTrue(csv.contains("\"Last day (UTC)\",\"2026-11-22\""));
        assertTrue(csv.contains("\"Filters\",\"Result: Done; Record: 300000000001\""), csv);
        assertTrue(csv.contains("\"Events\",\"2\""));
        assertTrue(csv.contains("\r\n\r\n" + AuditCsv.HEADER + "\r\n"));
        assertTrue(csv.contains(DOC.toString()), "document IDs are in the report");
        assertTrue(csv.contains("\"300000000001\""), "record identifiers are in the report");
        assertFalse(csv.contains("secret-loan-agreement"), "never a file name");
        assertFalse(csv.contains("Jane Borrower"), "never a title");
        assertFalse(csv.contains("Top secret reason"), "never a reason");
        // The period is whole UTC days, the last one included; the filters are passed on as the Audit list's.
        ArgumentCaptor<AuditQueryService.SearchRequest> search = ArgumentCaptor.forClass(AuditQueryService.SearchRequest.class);
        verify(audits).sealedEntries(eq(TENANT), search.capture());
        assertEquals(Instant.parse("2026-11-01T00:00:00Z"), search.getValue().from());
        assertEquals(Instant.parse("2026-11-22T23:59:59.999999Z"), search.getValue().to());
        assertEquals(AuditOutcome.SUCCESS, search.getValue().outcome());
        assertEquals("300000000001", search.getValue().recordNumber());
        assertEquals(2, report.rowCount());
        assertEquals(Instant.parse("2026-11-23T00:00:00Z"), report.to());
    }

    @Test
    void theFingerprintIsTheSha256OfTheCsvAndTheGenerationIsAudited() {
        when(audits.sealedEntries(eq(TENANT), any())).thenReturn(entries());
        SealedAuditReportService.Report report = service.generate(PRIYA, days("2026-11-01", "2026-11-22"));

        byte[] csv = register.only().csv();
        assertEquals(SealedAuditReportService.sha256(csv), report.fingerprint());
        assertTrue(report.fingerprint().matches("[0-9a-f]{64}"));
        AuditEvent generated = events.get(0);
        assertEquals(SealedAuditReportService.GENERATED_ACTION, generated.action());
        assertEquals(report.reportId().toString(), generated.targetId());
        assertTrue(generated.safeDetailsJson().contains(report.fingerprint()));
        assertTrue(generated.safeDetailsJson().contains("\"rowCount\":2"));
        assertFalse(generated.safeDetailsJson().contains("secret"), "the audit holds no content either");
        // The CSV download is exactly the sealed file, and the copy is audited.
        SealedAuditReportService.Download copy = service.csv(PRIYA, report.reportId().toString());
        assertArrayEquals(csv, copy.bytes());
        assertTrue(copy.filename().matches("vero-audit-report-2026-11-01-to-2026-11-22-[0-9a-f]{8}\\.csv"), copy.filename());
        assertEquals(SealedAuditReportService.DOWNLOADED_ACTION, events.get(1).action());
    }

    @Test
    void verifyPassesForTheUnchangedFileAndFailsForAChangedOne() {
        when(audits.sealedEntries(eq(TENANT), any())).thenReturn(entries());
        SealedAuditReportService.Report report = service.generate(PRIYA, days("2026-11-01", "2026-11-22"));
        byte[] csv = register.only().csv();

        SealedAuditReportService.Verification same = service.verify(PRIYA, SealedAuditReportService.sha256(csv).toUpperCase());
        assertTrue(same.matches());
        assertEquals(report.reportId(), same.report().reportId());
        assertEquals("Priya Natarajan", same.report().generatedBy());

        byte[] changed = csv.clone();
        int at = new String(csv, StandardCharsets.UTF_8).lastIndexOf("Maya");
        changed[at] = 'N';
        SealedAuditReportService.Verification other = service.verify(PRIYA, SealedAuditReportService.sha256(changed));
        assertFalse(other.matches());
        assertNull(other.report());
        // Another entity's admin never matches this entity's report.
        SealedAuditReportService.Actor elsewhere = new SealedAuditReportService.Actor(OTHER, "it", "IT", "c");
        assertFalse(service.verify(elsewhere, report.fingerprint()).matches());
        assertEquals(List.of(SealedAuditReportService.GENERATED_ACTION, SealedAuditReportService.VERIFIED_ACTION,
                        SealedAuditReportService.VERIFIED_ACTION, SealedAuditReportService.VERIFIED_ACTION),
                events.stream().map(AuditEvent::action).toList());
        assertTrue(events.get(1).safeDetailsJson().contains("\"matches\":true"));
        assertTrue(events.get(2).safeDetailsJson().contains("\"matches\":false"));
    }

    @Test
    void aFingerprintThatIsNotSha256IsRefused() {
        CodedRefusal refusal = assertThrows(CodedRefusal.BadRequest.class, () -> service.verify(PRIYA, "not-a-fingerprint"));
        assertEquals("SDV-AUD-015", refusal.errorCode().code());
        assertTrue(events.isEmpty());
    }

    @Test
    void thePdfIsMadeFromTheSealedCsvWithItsStampAndFingerprint() throws Exception {
        when(audits.sealedEntries(eq(TENANT), any())).thenReturn(entries());
        SealedAuditReportService.Report report = service.generate(PRIYA, days("2026-11-01", "2026-11-22"));

        SealedAuditReportService.Download pdf = service.pdf(PRIYA, report.reportId().toString());
        assertTrue(new String(pdf.bytes(), 0, 5, StandardCharsets.US_ASCII).startsWith("%PDF-"));
        assertTrue(pdf.filename().endsWith(".pdf"));
        String text;
        try (PDDocument document = Loader.loadPDF(pdf.bytes())) {
            text = new PDFTextStripper().getText(document);
        }
        String flat = text.replaceAll("\\s+", " ");
        assertTrue(flat.contains("Vero sealed audit report"));
        assertTrue(flat.contains(report.fingerprint().substring(0, 40)), "the CSV's fingerprint is on the PDF");
        assertTrue(flat.contains("Priya Natarajan"));
        assertTrue(flat.contains("300000000001"));
        assertTrue(flat.contains("Confidential"));
        assertFalse(flat.contains("secret-loan-agreement"));
        assertFalse(flat.contains("Top secret reason"));
        assertEquals("PDF", events.get(1).safeDetailsJson().replaceAll(".*\"format\":\"([A-Z]+)\".*", "$1"));
    }

    @Test
    void aReportOverTheLimitIsRefusedAndNothingIsRecorded() {
        when(audits.sealedEntries(eq(TENANT), any())).thenThrow(new AuditQueryService.ExportTooLargeException("too big"));
        CodedRefusal refusal = assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA, days("2020-01-01", "2026-11-22")));
        assertEquals("SDV-AUD-013", refusal.errorCode().code());
        assertTrue(register.reports.isEmpty());
        assertTrue(events.isEmpty());
    }

    @Test
    void theDaysAndFiltersAreChecked() {
        assertEquals("SDV-AUD-011", assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA, days("2026-11-22", "2026-11-01"))).errorCode().code());
        assertEquals("SDV-AUD-011", assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA, days("22/11/2026", "2026-11-23"))).errorCode().code());
        assertEquals("SDV-AUD-011", assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA, days(null, "2026-11-23"))).errorCode().code());
        assertEquals("SDV-AUD-011", assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA, days("2026-02-30", "2026-03-01"))).errorCode().code());
        assertEquals("SDV-AUD-012", assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA,
                new SealedAuditReportService.ReportRequest("2026-11-01", "2026-11-02", null, "MAYBE", null, null))).errorCode().code());
        assertEquals("SDV-AUD-012", assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA,
                new SealedAuditReportService.ReportRequest("2026-11-01", "2026-11-02", "not a code", null, null, null))).errorCode().code());
        when(audits.sealedEntries(eq(TENANT), any())).thenThrow(new IllegalArgumentException("level"));
        assertEquals("SDV-AUD-012", assertThrows(CodedRefusal.BadRequest.class, () -> service.generate(PRIYA,
                new SealedAuditReportService.ReportRequest("2026-11-01", "2026-11-02", null, null, null, "SECRET"))).errorCode().code());
        assertTrue(register.reports.isEmpty());
        assertTrue(events.isEmpty());
    }

    @Test
    void whenTheRegisterCantBeWrittenNothingIsHandedOut() {
        when(audits.sealedEntries(eq(TENANT), any())).thenReturn(entries());
        register.failing = true;
        assertThrows(InternalCheckFailed.class, () -> service.generate(PRIYA, days("2026-11-01", "2026-11-22")));
    }

    @Test
    void anotherEntitysReportIsNotFound() {
        when(audits.sealedEntries(eq(TENANT), any())).thenReturn(entries());
        SealedAuditReportService.Report report = service.generate(PRIYA, days("2026-11-01", "2026-11-22"));
        SealedAuditReportService.Actor elsewhere = new SealedAuditReportService.Actor(OTHER, "it", "IT", "c");
        assertEquals("SDV-AUD-014", assertThrows(CodedRefusal.NotFound.class, () -> service.csv(elsewhere, report.reportId().toString())).errorCode().code());
        assertEquals("SDV-AUD-014", assertThrows(CodedRefusal.NotFound.class, () -> service.pdf(PRIYA, "not-a-reference")).errorCode().code());
        assertEquals(1, service.list(PRIYA).size());
        assertTrue(service.list(elsewhere).isEmpty());
    }

    /** The register in memory: insert and read only, as the table allows. */
    static final class Register implements AuditReportRepository {
        final List<StoredReport> reports = new ArrayList<>();
        boolean failing;

        StoredReport only() {
            assertEquals(1, reports.size());
            return reports.get(0);
        }

        @Override
        public void insert(StoredReport report) {
            if (failing) throw new IllegalStateException("database down");
            reports.add(report);
        }

        @Override
        public Optional<StoredReport> find(UUID tenantId, UUID reportId) {
            return reports.stream().filter(r -> r.tenantId().equals(tenantId) && r.reportId().equals(reportId)).findFirst();
        }

        @Override
        public List<StoredReport> list(UUID tenantId, int limit) {
            return reports.stream().filter(r -> r.tenantId().equals(tenantId))
                    .sorted(Comparator.comparing(StoredReport::generatedAt).reversed()).limit(limit).toList();
        }

        @Override
        public List<StoredReport> findByFingerprint(UUID tenantId, String fingerprint) {
            return reports.stream().filter(r -> r.tenantId().equals(tenantId) && r.fingerprint().equals(fingerprint)).toList();
        }
    }
}
