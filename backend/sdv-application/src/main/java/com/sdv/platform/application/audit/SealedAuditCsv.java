package com.sdv.platform.application.audit;

import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import static com.sdv.platform.application.audit.AuditCsv.cell;

/**
 * Task 0050: the sealed audit report as CSV (UTF-8 with a byte-order mark). First its stamp, one "name","value" line
 * each: the title, the report reference, who generated it, when, the first and last day (UTC), the filters and the
 * number of events. Then an empty line, and the events exactly as the audit export writes them ({@link AuditCsv}):
 * document IDs and record identifiers, never content, file names, titles or reasons. The SHA-256 fingerprint is over
 * this whole file, so the stamp is sealed too.
 */
public final class SealedAuditCsv {
    /** The stamp's names, in order (the PDF reads them back). */
    static final String REPORT = "Report";
    static final String GENERATED_BY = "Generated by";
    static final String GENERATED_AT = "Generated at (UTC)";
    static final String FIRST_DAY = "First day (UTC)";
    static final String LAST_DAY = "Last day (UTC)";
    static final String FILTERS = "Filters";
    static final String EVENTS = "Events";

    private SealedAuditCsv() { }

    /** to: the end of the period, not included (the start of the day after the last day). */
    record Stamp(UUID reportId, String generatedBy, Instant generatedAt, Instant from, Instant to,
                 Map<String, String> filters, int rowCount) { }

    static byte[] write(Stamp stamp, List<AuditQueryService.AuditEntry> entries) {
        StringBuilder out = new StringBuilder("﻿");
        out.append(cell(SealedAuditReportService.TITLE)).append("\r\n");
        line(out, REPORT, stamp.reportId().toString());
        line(out, GENERATED_BY, stamp.generatedBy());
        line(out, GENERATED_AT, stamp.generatedAt().toString());
        line(out, FIRST_DAY, stamp.from().atZone(ZoneOffset.UTC).toLocalDate().toString());
        line(out, LAST_DAY, stamp.to().atZone(ZoneOffset.UTC).toLocalDate().minusDays(1).toString());
        line(out, FILTERS, filterWords(stamp.filters()));
        line(out, EVENTS, Integer.toString(stamp.rowCount()));
        out.append("\r\n").append(AuditCsv.HEADER).append("\r\n");
        AuditCsv.appendRows(out, entries);
        return out.toString().getBytes(StandardCharsets.UTF_8);
    }

    /** "Result: Refused; Record: 300000000001", or "None". */
    static String filterWords(Map<String, String> filters) {
        if (filters == null || filters.isEmpty()) return "None";
        List<String> parts = new ArrayList<>();
        if (filters.containsKey("action")) parts.add("Action code: " + filters.get("action"));
        if (filters.containsKey("outcome")) parts.add("Result: " + AuditSentences.resultWords(filters.get("outcome")));
        if (filters.containsKey("recordNumber")) parts.add("Record: " + filters.get("recordNumber"));
        if (filters.containsKey("sensitivityLevel")) parts.add("Level: " + filters.get("sensitivityLevel"));
        return String.join("; ", parts);
    }

    private static void line(StringBuilder out, String name, String value) {
        out.append(cell(name)).append(',').append(cell(value)).append("\r\n");
    }

    /**
     * The file read back into lines of cells (quoted cells, doubled quotes, CR LF), for the PDF. The formula guard's
     * leading apostrophe is kept, as a spreadsheet would show it.
     */
    static List<List<String>> read(byte[] csv) {
        String text = new String(csv, StandardCharsets.UTF_8);
        if (text.startsWith("﻿")) text = text.substring(1);
        List<List<String>> lines = new ArrayList<>();
        List<String> line = new ArrayList<>();
        StringBuilder cell = new StringBuilder();
        boolean quoted = false;
        boolean any = false;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (quoted) {
                if (c == '"') {
                    if (i + 1 < text.length() && text.charAt(i + 1) == '"') { cell.append('"'); i++; }
                    else quoted = false;
                } else cell.append(c);
            } else if (c == '"') {
                quoted = true; any = true;
            } else if (c == ',') {
                line.add(cell.toString()); cell.setLength(0); any = true;
            } else if (c == '\r') {
                // part of CR LF
            } else if (c == '\n') {
                if (any || cell.length() > 0) line.add(cell.toString());
                lines.add(line);
                line = new ArrayList<>(); cell.setLength(0); any = false;
            } else {
                cell.append(c); any = true;
            }
        }
        if (any || cell.length() > 0) { line.add(cell.toString()); lines.add(line); }
        return lines;
    }
}
